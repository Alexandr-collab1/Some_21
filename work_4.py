class Rectangle:
    def __init__(self, width, height):
        self.width = width
        self.height = height

def calculate_area(self):
    result = self.width * self.height
    print(result)
def calculate_perimetr(self):
    result = 2*(self.width + self.height)
    print(result)

Pr_1 = Rectangle(100, 50)
calculate_area(Pr_1)
calculate_perimetr(Pr_1)